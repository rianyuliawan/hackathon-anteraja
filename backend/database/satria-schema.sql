-- Satria hackathon: PostgreSQL schema for the agreed logical model.
-- Apply as a migration to an empty database. No DROP statements are included.
-- Business transitions and authorization are enforced by Laravel services.
-- Demo data uses one clothing seller and several Jakarta hubs. Each shipment
-- visits one selected delivery hub; inter-hub transit is out of scope.
-- Photo refs are private storage keys, never public URLs or image bytes.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL, -- Laravel password hash, never plaintext
    name TEXT NOT NULL,
    phone TEXT,
    default_address TEXT,
    default_postcode VARCHAR(10),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    remember_token VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE hubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    address TEXT,
    latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((latitude IS NULL) = (longitude IS NULL))
);

CREATE TABLE user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    role TEXT NOT NULL CHECK (role IN ('BUYER','SELLER','COURIER','HUB_OPERATOR','OPS_ADMIN')),
    hub_id BIGINT REFERENCES hubs(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((role = 'HUB_OPERATOR' AND hub_id IS NOT NULL)
        OR (role <> 'HUB_OPERATOR' AND hub_id IS NULL))
);
CREATE UNIQUE INDEX user_roles_global_unique ON user_roles(user_id, role) WHERE hub_id IS NULL;
CREATE UNIQUE INDEX user_roles_hub_unique ON user_roles(user_id, role, hub_id) WHERE hub_id IS NOT NULL;

CREATE TABLE service_zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hub_id BIGINT NOT NULL REFERENCES hubs(id),
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (hub_id, code),
    UNIQUE (hub_id, id)
);

CREATE TABLE postal_coverages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    postcode VARCHAR(10) NOT NULL,
    purpose TEXT NOT NULL CHECK (purpose IN ('ORIGIN','DELIVERY')),
    hub_id BIGINT NOT NULL REFERENCES hubs(id),
    zone_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    FOREIGN KEY (hub_id, zone_id) REFERENCES service_zones(hub_id, id),
    UNIQUE (postcode, purpose)
);

CREATE TABLE hub_links (
    from_hub_id BIGINT NOT NULL REFERENCES hubs(id),
    to_hub_id BIGINT NOT NULL REFERENCES hubs(id),
    routing_cost INTEGER NOT NULL DEFAULT 1 CHECK (routing_cost > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (from_hub_id, to_hub_id),
    CHECK (from_hub_id <> to_hub_id)
);

CREATE TABLE seller_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    store_name TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE seller_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_user_id BIGINT NOT NULL REFERENCES seller_profiles(user_id),
    address TEXT NOT NULL,
    postcode VARCHAR(10) NOT NULL,
    contact_name TEXT NOT NULL,
    contact_phone TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (seller_user_id, id)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_user_id BIGINT NOT NULL REFERENCES seller_profiles(user_id),
    sku TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    price NUMERIC(14,2) NOT NULL CHECK (price >= 0),
    weight_grams INTEGER NOT NULL CHECK (weight_grams > 0),
    length_mm INTEGER NOT NULL CHECK (length_mm > 0),
    width_mm INTEGER NOT NULL CHECK (width_mm > 0),
    height_mm INTEGER NOT NULL CHECK (height_mm > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no TEXT NOT NULL UNIQUE,
    checkout_key TEXT NOT NULL UNIQUE,
    channel TEXT NOT NULL DEFAULT 'CATALOG' CHECK (channel IN ('CATALOG','MANUAL')),
    customer_id BIGINT NOT NULL REFERENCES users(id),
    seller_user_id BIGINT NOT NULL REFERENCES seller_profiles(user_id),
    seller_location_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING_APPROVAL'
        CHECK (status IN ('PENDING_APPROVAL','APPROVED','REJECTED','CANCELLED')),
    origin_address_snapshot TEXT NOT NULL,
    origin_contact_snapshot TEXT NOT NULL,
    origin_postcode VARCHAR(10) NOT NULL,
    destination_address_snapshot TEXT NOT NULL,
    destination_latitude NUMERIC(9,6) CHECK (destination_latitude BETWEEN -90 AND 90),
    destination_longitude NUMERIC(9,6) CHECK (destination_longitude BETWEEN -180 AND 180),
    recipient_name TEXT NOT NULL,
    recipient_phone TEXT NOT NULL,
    destination_postcode VARCHAR(10) NOT NULL,
    estimated_weight_grams INTEGER NOT NULL CHECK (estimated_weight_grams > 0),
    estimated_length_mm INTEGER NOT NULL CHECK (estimated_length_mm > 0),
    estimated_width_mm INTEGER NOT NULL CHECK (estimated_width_mm > 0),
    estimated_height_mm INTEGER NOT NULL CHECK (estimated_height_mm > 0),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    shipping_fee NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (shipping_fee >= 0),
    reviewed_by BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMPTZ,
    rejection_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (seller_user_id, seller_location_id)
        REFERENCES seller_locations(seller_user_id, id),
    CHECK (status <> 'REJECTED' OR rejection_reason IS NOT NULL),
    CHECK ((destination_latitude IS NULL) = (destination_longitude IS NULL))
);
CREATE INDEX orders_customer_created_idx ON orders(customer_id, created_at DESC);
CREATE INDEX orders_status_idx ON orders(status);

CREATE TABLE order_items (
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    product_name_snapshot TEXT NOT NULL,
    price_snapshot NUMERIC(14,2) NOT NULL CHECK (price_snapshot >= 0),
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE courier_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    home_hub_id BIGINT NOT NULL REFERENCES hubs(id),
    max_parcels INTEGER NOT NULL DEFAULT 20 CHECK (max_parcels > 0),
    max_weight_grams INTEGER NOT NULL DEFAULT 20000 CHECK (max_weight_grams > 0),
    available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE courier_zones (
    courier_user_id BIGINT NOT NULL REFERENCES courier_profiles(user_id),
    zone_id BIGINT NOT NULL REFERENCES service_zones(id),
    service_type TEXT NOT NULL CHECK (service_type IN ('PICKUP','DELIVERY')),
    PRIMARY KEY (courier_user_id, zone_id, service_type)
);

CREATE TABLE shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
    awb VARCHAR(40) NOT NULL UNIQUE,
    origin_hub_id BIGINT NOT NULL REFERENCES hubs(id),
    delivery_hub_id BIGINT NOT NULL REFERENCES hubs(id),
    pickup_zone_id BIGINT NOT NULL,
    delivery_zone_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'WAITING_SELLER_READY'
        CHECK (status IN ('WAITING_SELLER_READY','READY_FOR_PICKUP','PICKUP_ASSIGNED',
            'PICKED_UP','AT_HUB','IN_TRANSIT','READY_FOR_LAST_MILE',
            'DELIVERY_ASSIGNED','OUT_FOR_DELIVERY','DELIVERY_FAILED',
            'AT_HUB_AWAITING_DECISION','WAITING_REDELIVERY','DELIVERED',
            'RETURN_REQUESTED','RETURNED_TO_SELLER','EXCEPTION')),
    custody_type TEXT NOT NULL DEFAULT 'SELLER'
        CHECK (custody_type IN ('SELLER','COURIER','HUB','IN_TRANSIT','RECIPIENT')),
    current_hub_id BIGINT REFERENCES hubs(id),
    current_courier_id BIGINT REFERENCES courier_profiles(user_id),
    delivered_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (origin_hub_id, pickup_zone_id) REFERENCES service_zones(hub_id, id),
    FOREIGN KEY (delivery_hub_id, delivery_zone_id) REFERENCES service_zones(hub_id, id)
);
CREATE INDEX shipments_status_hub_idx ON shipments(status, current_hub_id);

CREATE TABLE parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(id),
    parcel_no INTEGER NOT NULL DEFAULT 1 CHECK (parcel_no > 0),
    weight_grams INTEGER NOT NULL CHECK (weight_grams > 0),
    length_mm INTEGER NOT NULL CHECK (length_mm > 0),
    width_mm INTEGER NOT NULL CHECK (width_mm > 0),
    height_mm INTEGER NOT NULL CHECK (height_mm > 0),
    measured_at TIMESTAMPTZ,
    UNIQUE (shipment_id, parcel_no)
);

CREATE TABLE route_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(id),
    version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    change_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (shipment_id, version)
);
CREATE UNIQUE INDEX route_plans_one_active_idx ON route_plans(shipment_id) WHERE active;

CREATE TABLE route_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_plan_id BIGINT NOT NULL REFERENCES route_plans(id),
    sequence_no INTEGER NOT NULL CHECK (sequence_no > 0),
    hub_id BIGINT NOT NULL REFERENCES hubs(id),
    arrived_at TIMESTAMPTZ,
    departed_at TIMESTAMPTZ,
    UNIQUE (route_plan_id, sequence_no)
);

CREATE TABLE pickup_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL UNIQUE REFERENCES shipments(id),
    status TEXT NOT NULL DEFAULT 'WAITING_SELLER_READY'
        CHECK (status IN ('WAITING_SELLER_READY','READY_FOR_PICKUP','ASSIGNED',
            'PICKED_UP','CANCELLED')),
    ready_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE pickup_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pickup_task_id BIGINT NOT NULL REFERENCES pickup_tasks(id),
    courier_user_id BIGINT NOT NULL REFERENCES courier_profiles(user_id),
    assigned_by BIGINT NOT NULL REFERENCES users(id),
    status TEXT NOT NULL DEFAULT 'PENDING_ACCEPT'
        CHECK (status IN ('PENDING_ACCEPT','ACCEPTED','IN_PROGRESS','REJECTED',
            'EXPIRED','COMPLETED','FAILED','CANCELLED')),
    scheduled_at TIMESTAMPTZ,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at TIMESTAMPTZ,
    picked_up_at TIMESTAMPTZ,
    failed_at TIMESTAMPTZ,
    reject_reason TEXT,
    failure_reason TEXT,
    pickup_photo_ref TEXT,
    CHECK (status <> 'COMPLETED' OR
        (picked_up_at IS NOT NULL AND pickup_photo_ref IS NOT NULL
         AND btrim(pickup_photo_ref) <> ''))
);
CREATE UNIQUE INDEX pickup_assignments_one_active_idx ON pickup_assignments(pickup_task_id)
    WHERE status IN ('PENDING_ACCEPT','ACCEPTED','IN_PROGRESS');

CREATE TABLE delivery_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hub_id BIGINT NOT NULL REFERENCES hubs(id),
    zone_id BIGINT NOT NULL,
    courier_user_id BIGINT NOT NULL REFERENCES courier_profiles(user_id),
    assigned_by BIGINT NOT NULL REFERENCES users(id),
    service_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING_ACCEPT'
        CHECK (status IN ('PENDING_ACCEPT','ACCEPTED','REJECTED','EXPIRED',
            'OUT_FOR_DELIVERY','COMPLETED','CANCELLED')),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at TIMESTAMPTZ,
    FOREIGN KEY (hub_id, zone_id) REFERENCES service_zones(hub_id, id)
);
CREATE INDEX delivery_runs_courier_date_idx ON delivery_runs(courier_user_id, service_date);

CREATE TABLE run_shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES delivery_runs(id),
    shipment_id BIGINT NOT NULL REFERENCES shipments(id),
    stop_order INTEGER NOT NULL CHECK (stop_order > 0),
    status TEXT NOT NULL DEFAULT 'ASSIGNED'
        CHECK (status IN ('ASSIGNED','HANDED_OVER','DELIVERED','FAILED',
            'RETURNED_TO_HUB','CANCELLED')),
    handed_over_at TIMESTAMPTZ,
    returned_at TIMESTAMPTZ,
    rejection_reason TEXT,
    UNIQUE (run_id, shipment_id),
    UNIQUE (run_id, stop_order),
    UNIQUE (id, shipment_id)
);
CREATE UNIQUE INDEX run_shipments_one_active_idx ON run_shipments(shipment_id)
    WHERE status IN ('ASSIGNED','HANDED_OVER');

CREATE TABLE delivery_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_shipment_id BIGINT NOT NULL UNIQUE,
    shipment_id BIGINT NOT NULL REFERENCES shipments(id),
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0),
    result TEXT NOT NULL CHECK (result IN ('DELIVERED','FAILED')),
    failure_reason TEXT,
    notes TEXT,
    recipient_name TEXT,
    delivery_photo_ref TEXT,
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (shipment_id, attempt_no),
    FOREIGN KEY (run_shipment_id, shipment_id) REFERENCES run_shipments(id, shipment_id),
    CHECK ((result = 'FAILED' AND failure_reason IS NOT NULL)
        OR (result = 'DELIVERED' AND recipient_name IS NOT NULL
            AND delivery_photo_ref IS NOT NULL
            AND btrim(delivery_photo_ref) <> ''))
);

CREATE TABLE shipment_issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(id),
    delivery_attempt_id BIGINT NOT NULL UNIQUE REFERENCES delivery_attempts(id),
    status TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','RESOLVED')),
    decision TEXT CHECK (decision IN ('RESCHEDULE','RETURN_TO_SELLER')),
    decision_note TEXT,
    scheduled_redelivery_at TIMESTAMPTZ,
    decided_by BIGINT REFERENCES users(id),
    decided_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (status = 'OPEN' OR (decision IS NOT NULL AND decided_by IS NOT NULL AND decided_at IS NOT NULL))
);

CREATE TABLE tracking_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(id),
    actor_user_id BIGINT REFERENCES users(id),
    hub_id BIGINT REFERENCES hubs(id),
    event_type TEXT NOT NULL,
    status_after TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX tracking_events_shipment_time_idx ON tracking_events(shipment_id, occurred_at, id);

CREATE TABLE notification_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    hub_id BIGINT REFERENCES hubs(id),
    channel TEXT NOT NULL CHECK (channel IN ('TELEGRAM','WHATSAPP')),
    destination TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (num_nonnulls(user_id, hub_id) = 1)
);
CREATE UNIQUE INDEX notification_targets_user_channel_idx
    ON notification_targets(user_id, channel) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX notification_targets_hub_channel_idx
    ON notification_targets(hub_id, channel) WHERE hub_id IS NOT NULL;

-- Optional verified Telegram peer link for recipients who choose to pair.
-- LIVE delivery can also resolve users.phone through the private MTProto adapter.
-- Session/access hashes stay in the adapter, never in this database.
CREATE TABLE telegram_pairing_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    code_hash TEXT NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (expires_at > created_at)
);
CREATE INDEX telegram_pairing_requests_user_idx
    ON telegram_pairing_requests(user_id, created_at DESC);

CREATE TABLE telegram_links (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    peer_id BIGINT NOT NULL UNIQUE,
    username TEXT,
    verified_at TIMESTAMPTZ NOT NULL,
    consented_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (revoked_at IS NULL OR revoked_at >= consented_at)
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_event_id BIGINT REFERENCES tracking_events(id),
    shipment_id BIGINT REFERENCES shipments(id),
    target_id BIGINT NOT NULL REFERENCES notification_targets(id),
    logical_recipient TEXT NOT NULL CHECK (logical_recipient IN
        ('BUYER','SELLER','COURIER','OPS_ADMIN','HUB_OPERATOR')),
    template_key TEXT NOT NULL,
    message_text TEXT NOT NULL,
    action_url TEXT,
    actual_destination TEXT,
    channel TEXT NOT NULL CHECK (channel IN ('TELEGRAM','WHATSAPP')),
    delivery_mode TEXT NOT NULL DEFAULT 'MOCK' CHECK (delivery_mode IN ('MOCK','LIVE')),
    status TEXT NOT NULL DEFAULT 'QUEUED'
        CHECK (status IN ('QUEUED','SENDING','SENT','FAILED','SIMULATED')),
    dedupe_key TEXT NOT NULL UNIQUE,
    provider_message_id TEXT,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error TEXT,
    sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (status <> 'SIMULATED' OR delivery_mode = 'MOCK'),
    CHECK (status <> 'SENT' OR
        (delivery_mode = 'LIVE' AND provider_message_id IS NOT NULL
         AND sent_at IS NOT NULL))
);
CREATE INDEX notifications_pending_idx ON notifications(status, created_at);

CREATE TABLE daily_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_date DATE NOT NULL,
    hub_id BIGINT NOT NULL REFERENCES hubs(id),
    shipments_created INTEGER NOT NULL DEFAULT 0,
    delivered INTEGER NOT NULL DEFAULT 0,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    redelivered INTEGER NOT NULL DEFAULT 0,
    returned_requested INTEGER NOT NULL DEFAULT 0,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (report_date, hub_id)
);

-- Final delivery results and tracking history are append-only. Insert a new row
-- for a new delivery attempt or correction; never overwrite an earlier attempt.
CREATE OR REPLACE FUNCTION prevent_audit_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Audit rows are append-only';
END;
$$;
CREATE TRIGGER delivery_attempts_append_only
    BEFORE UPDATE OR DELETE ON delivery_attempts
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
CREATE TRIGGER tracking_events_append_only
    BEFORE UPDATE OR DELETE ON tracking_events
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_mutation();
